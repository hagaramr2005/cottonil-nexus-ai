export type Key = keyof typeof D
// A missing key must degrade to visible text, never throw and blank the whole app.
export const t = (lang: Lang, key: Key): string => D[key]?.[lang] ?? String(key)

const loc = (lang: Lang) => (lang === 'ar' ? 'ar-EG-u-nu-latn' : 'en-US')
export function fmtNumber(lang: Lang, n: number | null | undefined, opts: Intl.NumberFormatOptions = {}): string {
  if (n == null || Number.isNaN(n)) return t(lang, 'na')
  return new Intl.NumberFormat(loc(lang), { maximumFractionDigits: 2, ...opts }).format(n)
}
export const fmtCompact = (lang: Lang, n: number | null | undefined) =>
  n == null ? t(lang, 'na') : new Intl.NumberFormat(loc(lang), { notation: 'compact', maximumFractionDigits: 2 }).format(n)
export function fmtMoney(lang: Lang, n: number | null | undefined, unit = 'EGP', compact = true): string {
  if (n == null || Number.isNaN(n)) return t(lang, 'na')
  const body = compact && Math.abs(n) >= 1_000_000 ? fmtCompact(lang, n) : fmtNumber(lang, n)
  const u = unit === 'EGP' ? (lang === 'ar' ? 'ج.م' : 'EGP') : unit
  return u ? `${body} ${u}` : body
}
/** Splits a money amount into the numeric run (always LTR digits) and the unit words (follow the page direction). */
export function moneyParts(lang: Lang, n: number | null | undefined, unit = 'EGP', compact = true): { num: string; word: string } {
  if (n == null || Number.isNaN(n)) return { num: t(lang, 'na'), word: '' }
  const u = unit === 'EGP' ? (lang === 'ar' ? 'ج.م' : 'EGP') : unit
  const big = compact && Math.abs(n) >= 1_000_000
  const parts = new Intl.NumberFormat(loc(lang), { maximumFractionDigits: 2, ...(big ? { notation: 'compact' as const } : {}) }).formatToParts(n)
  const num = parts.filter((p) => p.type !== 'compact').map((p) => p.value).join('').trim()
  const comp = parts.filter((p) => p.type === 'compact').map((p) => p.value).join('').trim()
  return { num, word: [comp, u].filter(Boolean).join(' ') }
}
export const fmtDate = (lang: Lang, iso?: string | null) => {
  if (!iso) return '—'
  const d = new Date(iso)
  return Number.isNaN(d.getTime()) ? iso : new Intl.DateTimeFormat(loc(lang), { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(d)
}
